let current = 'ru';

// lang — текущий язык.
export function lang() {
  return current;
}

// setLang — сменить язык; неизвестный код — без изменений. Возвращает текущий язык.
export function setLang(code) {
  if (LANGS.includes(code)) current = code;
  return current;
}

// pickLang — первый известный язык из списка кодов ('zh-CN' → 'zh', 'en_US' → 'en'); нет — ''.
export function pickLang(codes) {
  for (const c of codes || []) {
    const base = String(c || '').trim().toLowerCase().split(/[-_]/)[0];
    if (LANGS.includes(base)) return base;
  }
  return '';
}

// locale — локаль для дат и чисел.
export function locale() {
  return LOCALES[current];
}

// t — текст ключа на текущем языке с подстановкой {0}, {1}, …
export function t(key, ...args) {
  const s = DICT[current][key] ?? DICT.ru[key] ?? key;
  return s.replace(/\{(\d)\}/g, (m, i) => (args[i] === undefined ? m : String(args[i])));
}

// keys — ключи словаря языка (проверка полноты в тестах).
export function keys(code) {
  return Object.keys(DICT[code] || {});
}
